// Generate engine/baseBowl.ts: the start state for bowling practice (you bowl, the computer bats).
// Reads the full-RAM snapshot recorded by analysis/tools/p3/gen_bowl_base.py, plays many balls with
// random bowling and fielding input on a TrackingRam (both fielding options), and keeps only the RAM
// the session reads from its start state (as ranges).
//
// usage: npx tsx src/apps/console/cricket/tools/genBowlBase.ts RAM.bin CTX.json [balls]
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { TrackingRam, Ram } from "../engine/mem";
import { Practice, DEFAULT_SETTINGS, PAD } from "../engine/practice";
import type { Settings } from "../engine/practice";

const [ramFile, ctxFile, nBalls = "200"] = process.argv.slice(2);
const full = new Uint8Array(readFileSync(ramFile));
const ctx = JSON.parse(readFileSync(ctxFile, "utf8")).ctx;
const trackers: TrackingRam[] = [];
const start = (_s: Settings): Ram => { const t = new TrackingRam(full); trackers.push(t); return t; };

let rnd = 4242;
const rand = (n: number) => { rnd = (rnd * 1103515245 + 12345) & 0x7fffffff; return rnd % n; };
const DIRS = [PAD.U, PAD.D, PAD.L, PAD.R, PAD.U | PAD.L, PAD.U | PAD.R, PAD.D | PAD.L, PAD.D | PAD.R, 0];
const kinds: Settings["bowler"][] = ["fast", "swing", "spin"];
const counts: Record<string, number> = {};
let steps = 0;
for (const humanField of [true, false]) {
  const base: Settings = { ...DEFAULT_SETTINGS, mode: "bowl", humanField };
  const g = new Practice(11, base, start);
  for (let b = 0; b < Number(nBalls); b++) {
    g.nextBall({ ...base, bowler: kinds[b % 3], leftArm: b % 5 === 0, difficulty: (b % 3) as 0 | 1 | 2, accuracy: rand(100) });
    let held = 0, t = 0, hold = 0, cur = 0;
    while (g.phase !== "result" && t < 8000) {
      if (hold-- <= 0) {
        // random pad script like bowl_batch.py: directions for a while, A taps, and in the field B/C too
        const r = rand(10);
        cur = r < 5 ? DIRS[rand(9)] : r < 8 ? PAD.A : g.phase === "field" ? [PAD.B, PAD.C, PAD.A | PAD.U][rand(3)] : 0;
        hold = 2 + rand(30);
      }
      g.tick({ held: cur, pressed: cur & ~held });
      g.view();
      held = cur; t++; steps++;
    }
    const r = g.result;
    counts[r ? r.outcome : "timeout"] = (counts[r ? r.outcome : "timeout"] ?? 0) + 1;
  }
}
const union = new Uint8Array(0x10000);
for (const t of trackers) for (let i = 0; i < 0x10000; i++) if (t.readFirst[i]) union[i] = 1;
// plus every RAM range the committed bowling-side traces start from (deliveries, fielding views,
// hand-overs): rarely-read bytes a random session may miss
const tdir = join(dirname(fileURLToPath(import.meta.url)), "..", "traces");
const mark = (ram: unknown) => {
  if (!Array.isArray(ram)) return;
  for (const [a, b64] of ram as [number, string][]) { const n = Buffer.from(b64, "base64").length; for (let i = 0; i < n; i++) union[(a + i) & 0xffff] = 1; }
};
for (const [sub, re] of [["", /^bowl_/], ["field", /^bowl/], ["hand", /^bowl/]] as const) {
  for (const f of readdirSync(join(tdir, sub)).filter((f) => re.test(f))) {
    const tr = JSON.parse(gunzipSync(readFileSync(join(tdir, sub, f))).toString("utf8"));
    mark(tr.ram); mark(tr.target);
  }
}
const ranges: [number, number][] = [];
for (let i = 0; i < 0x10000; i++) {
  if (!union[i]) continue;
  const last = ranges[ranges.length - 1];
  if (last && i <= last[1] + 16) last[1] = i; else ranges.push([i, i]);
}
const lines = [
  "// GENERATED by tools/genBowlBase.ts (from analysis/tools/p3/gen_bowl_base.py). Do not edit.",
  "// Start state for bowling practice: the RAM ranges the engine reads, recorded from the original game",
  "// (Quick Start, England v Australia, Australia batting, you bowl with pad 1) just before a delivery is",
  "// set up. Contains values copied from the ROM (tables, player data): console/cricket branch only.",
  "",
  "export const BASE_RAM_BOWL: [number, string][] = [",
  ...ranges.map(([a, b]) => `  [0x${a.toString(16).padStart(4, "0")}, "${Buffer.from(full.subarray(a, b + 1)).toString("base64")}"],`),
  "];",
  `export const BASE_CONTEXT_BOWL = ${JSON.stringify(ctx)} as const;`,
  "",
];
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "engine", "baseBowl.ts"), lines.join("\n"));
console.log(counts, steps, "steps");
console.log(ranges.length, "ranges,", ranges.reduce((s, [a, b]) => s + b - a + 1, 0), "bytes");
