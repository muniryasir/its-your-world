// Writes engine/baseMatch.ts: the RAM a new match starts from (teams loaded, England v Australia), taken
// from the original right after the toss ($D9DA; analysis tools/p4/start_rec.py). All non-zero bytes
// are kept: the engine also reads a few places it does not model itself (pads, a stale frame pointer).
//
// usage: npx tsx tools/genMatchBase.ts START.bin [snapshot index, default 0]
import { readFileSync, writeFileSync } from "node:fs";
const all = readFileSync(process.argv[2]);
const k = +(process.argv[3] ?? 0);
const r = all.subarray(k * 0x10000, (k + 1) * 0x10000);
const out: string[] = [];
let bytes = 0;
for (let a = 0x400; a < 0x10000; a++) { // (below $400: the stack)
  if (r[a] === 0) continue;
  let b = a + 1, last = a;
  for (; b < 0x10000 && b - last <= 8; b++) if (r[b] !== 0) last = b;
  out.push(`  [0x${a.toString(16)}, "${Buffer.from(r.subarray(a, last + 1)).toString("base64")}"],`);
  bytes += last + 1 - a;
  a = last;
}
writeFileSync(new URL("../engine/baseMatch.ts", import.meta.url),
  `// GENERATED by tools/genMatchBase.ts (from analysis/tools/p4/start_rec.py). Do not edit.
// The RAM a match starts from, recorded from the original game right after the toss of a 10-over
// England v Australia match (teams and players loaded, nothing played). Contains values copied from
// the ROM (player data, tables): console/cricket branch only.

export const BASE_RAM_MATCH: [number, string][] = [
${out.join("\n")}
];
`);
console.log(`${out.length} ranges, ${bytes} bytes`);
